#!/usr/bin/env python3
"""Generate docs/llm/PROJECT_MAP.md from the repository file tree."""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "llm" / "PROJECT_MAP.md"
EXCLUDED_PARTS = {".git", "target", "node_modules", ".direnv", "book", "__pycache__"}
EXCLUDED_PATHS = {
    "crates/adventuresim-stdb-module/static/wasm",
    "crates/adventuresim-stdb-module/static/assets",
}


def tracked_files() -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=True,
    )
    files = []
    for raw_path in result.stdout.splitlines():
        path = raw_path.replace("\\", "/")
        if any(part in EXCLUDED_PARTS for part in Path(path).parts):
            continue
        if path.endswith((".pyc", ".pyo")):
            continue
        if path == OUTPUT.relative_to(ROOT).as_posix():
            continue
        if any(path == excluded or path.startswith(f"{excluded}/") for excluded in EXCLUDED_PATHS):
            continue
        files.append(path)
    return sorted(files)


def summary(path: str) -> str:
    name = Path(path).name
    parent = Path(path).parent.as_posix()
    if name == "Cargo.toml":
        return "Cargo package/workspace manifest."
    if name == "Cargo.lock":
        return "Locked Rust dependency versions."
    if name == "README.md":
        return "Component overview and usage notes."
    if name.endswith(".rs"):
        if name.endswith("_reducer.rs"):
            return "Generated SpacetimeDB reducer interface."
        if name.endswith("_table.rs"):
            return "Generated SpacetimeDB table interface."
        if name.endswith("_type.rs"):
            return "Generated SpacetimeDB data type."
        if "/src/routes/" in path:
            return "Strategic web HTTP route handler."
        if "/src/templates/" in path:
            return "Strategic web server-rendered template."
        if "/src/spacetimedb/" in path:
            return "Strategic web SpacetimeDB integration module."
        if parent.endswith("/src"):
            return "Rust source module for this component."
        return "Rust source module."
    if name.endswith(".md"):
        return "Project documentation."
    if name.endswith(".toml"):
        return "Tooling or build configuration."
    if name.endswith(".nix") or name.endswith(".lock"):
        return "Nix environment configuration or lockfile."
    if name.endswith(".sh") or name.endswith(".py"):
        return "Development or documentation automation script."
    if name.endswith(".html"):
        return "Browser UI page."
    if name.endswith(".css"):
        return "Browser UI styling."
    if name.endswith(".svg"):
        return "Vector UI or texture asset."
    if name.endswith((".png", ".ttf", ".glb")):
        return "Binary game or UI asset."
    if name == "Dockerfile":
        return "Container build definition."
    return "Repository support file."


def render() -> str:
    files = tracked_files()
    lines = [
        "# Project map",
        "",
        "Generated by `python scripts/update_project_map.py`; do not edit by hand.",
        "It inventories repository files that are relevant to implementation and orientation.",
        "Build output, Git internals, dependency directories, and generated browser artifacts are excluded.",
        "",
        "## How to use this map",
        "",
        "Start with `AGENTS.md`, then read the root README and the relevant architecture,",
        "development, or wiki document before changing a subsystem.",
        "",
        f"## Files ({len(files)})",
        "",
    ]
    lines.extend(f"- `{path}` — {summary(path)}" for path in files)
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the map is stale")
    args = parser.parse_args()
    content = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if args.check:
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date. Run: python scripts/update_project_map.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is current.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Updated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
